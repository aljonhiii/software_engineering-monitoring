import dotenv from 'dotenv';
import nodemailer from 'nodemailer';

dotenv.config();

const host = process.env.SMTP_HOST || 'smtp.gmail.com';
const port = parseInt(process.env.SMTP_PORT || '587', 10);
const secure = process.env.SMTP_SECURE === 'true' || port === 465;
const user = process.env.SMTP_USER ? String(process.env.SMTP_USER).trim() : '';
const pass = process.env.SMTP_PASS ? String(process.env.SMTP_PASS).replace(/\s+/g, '') : '';
const from = process.env.SMTP_FROM || `"KixCleen Platform" <${user}>`;

// Target recipient: allow command line arg (e.g. node scripts/testSmtp.js someone@example.com) or default to SMTP_USER
const targetRecipient = process.argv[2] || user;

console.log('================================================================');
console.log('📧 KIXCLEEN SMTP DIAGNOSTIC & VERIFICATION TOOL');
console.log('================================================================\n');

console.log('Configuration detected in backend/.env:');
console.log('• Host:        ', host);
console.log('• Port:        ', port);
console.log('• Secure (TLS):', secure ? 'true (Port 465)' : 'false (STARTTLS Port 587)');
console.log('• User:        ', user ? user : '⚠️  MISSING (SMTP_USER is not set)');
console.log('• App Password:', pass ? `Configured (${pass.length} characters)` : '⚠️  MISSING (SMTP_PASS is not set)');
console.log('• From Header: ', from);
console.log('• Send Test To:', targetRecipient);
console.log('----------------------------------------------------------------\n');

if (!user || !pass) {
  console.error('❌ FAILED: Missing SMTP_USER or SMTP_PASS in backend/.env.');
  console.error('Please configure your Gmail account and 16-character App Password.\n');
  process.exit(1);
}

const transporter = nodemailer.createTransport({
  host,
  port,
  secure,
  auth: { user, pass },
  tls: { rejectUnauthorized: false },
});

console.log('1️⃣  Verifying handshake & authentication with SMTP server...');
try {
  await transporter.verify();
  console.log('   ✅ Handshake successful! SMTP credentials are authenticated.\n');
} catch (err) {
  console.error('   ❌ Authentication failed with error:');
  console.error('   ', err.message);
  console.error('\nCommon fixes for Gmail:');
  console.error('• Ensure 2-Step Verification is enabled in your Google Account.');
  console.error('• Generate a dedicated 16-character "App Password" at https://myaccount.google.com/apppasswords');
  console.error('• Do NOT use your regular Gmail login password.\n');
  process.exit(1);
}

if (targetRecipient) {
  console.log(`2️⃣  Dispatching test email to ${targetRecipient}...`);
  try {
    const info = await transporter.sendMail({
      from,
      to: targetRecipient,
      subject: '✅ KixCleen SMTP Verification Test',
      text: `Hello!\n\nThis is a verification email from your KixCleen Monitoring Platform.\nYour SMTP settings in backend/.env are working properly!\n\nTimestamp: ${new Date().toLocaleString()}`,
      html: `
        <div style="font-family: Arial, sans-serif; max-width: 560px; margin: 0 auto; border: 1px solid #e2e8f0; border-radius: 12px; padding: 24px; background: #ffffff;">
          <h2 style="color: #0f172a; margin-top: 0;">👟 KixCleen Platform</h2>
          <div style="padding: 12px 16px; background: #ecfdf5; border-left: 4px solid #10b981; border-radius: 4px; margin-bottom: 20px;">
            <p style="margin: 0; color: #065f46; font-weight: bold;">✅ SMTP Connection Verified!</p>
            <p style="margin: 4px 0 0 0; color: #047857; font-size: 13px;">Your email dispatch service is online and operational.</p>
          </div>
          <p style="color: #475569; font-size: 14px; line-height: 1.6;">
            Your Gmail SMTP configuration is successfully connected to the KixCleen Monitoring backend.
          </p>
          <table style="width: 100%; border-collapse: collapse; font-size: 13px; margin: 16px 0;">
            <tr style="border-bottom: 1px solid #f1f5f9;">
              <td style="padding: 8px 0; color: #64748b;">SMTP Host</td>
              <td style="padding: 8px 0; color: #0f172a; font-weight: bold;">${host}:${port}</td>
            </tr>
            <tr style="border-bottom: 1px solid #f1f5f9;">
              <td style="padding: 8px 0; color: #64748b;">Authenticated As</td>
              <td style="padding: 8px 0; color: #0f172a; font-weight: bold;">${user}</td>
            </tr>
            <tr>
              <td style="padding: 8px 0; color: #64748b;">Delivered At</td>
              <td style="padding: 8px 0; color: #0f172a; font-weight: bold;">${new Date().toLocaleString()}</td>
            </tr>
          </table>
          <p style="color: #94a3b8; font-size: 12px; margin-bottom: 0;">This email was generated by your KixCleen diagnostic tool.</p>
        </div>
      `,
    });

    console.log('   ✅ Test email delivered successfully!');
    console.log('   Message ID:', info.messageId);
    console.log(`\n🎉 Check the inbox (or spam/junk folder) of ${targetRecipient}!\n`);
  } catch (err) {
    console.error('   ❌ Failed to send email:');
    console.error('   ', err.message, '\n');
    process.exit(1);
  }
}

console.log('================================================================');
console.log('✅ ALL SMTP TESTS PASSED');
console.log('================================================================\n');
